export function zodIssues(error: z.ZodError): string {
  return error.issues
    .map((issue) => {
      const path = issue.path.length === 0 ? "value" : issue.path.map(String).join(".");
      return `${path}: ${issue.message}`;
    })
    .join("; ");
}

export class CodePatrolError extends Error {
  constructor(
    readonly code: ErrorCode,
    message: string,
    readonly exitCode = ERROR_EXIT_CODES[code],
    readonly details?: unknown,
    options?: ErrorOptions,
  ) {
    super(message, options);
    this.name = "CodePatrolError";
  }
}

export function usage(message: string): never {
  throw new CodePatrolError(ERROR_CODES.USAGE, message);
}

export function assertDomain(
  condition: unknown,
  code: ErrorCode,
  message: string,
  details?: unknown,
): asserts condition {
  if (!condition) {
    throw new CodePatrolError(code, message, undefined, details);
  }
}
